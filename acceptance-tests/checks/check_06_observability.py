# check_06_observability.py (acceptance-tests/checks)
#
# Closes the loop on the specific customer-demo requirement this suite
# was built for: "a customer looks into the NAT server -- we should have
# everything in our observability." This check doesn't drive any traffic
# itself (checks 02/05 already do that) -- it verifies the OBSERVABILITY
# STACK ITSELF is actually up and actually has data, so a demo doesn't
# discover a blank Grafana panel live in front of a customer.
#
# -----------------------------------------------------
# What this verifies:
#
# 1) Prometheus (`control_plane.prometheus_url`) is reachable and its
#    `up{job="nat_exporter"}` target set is not empty -- i.e. Prometheus
#    is actually scraping real nodes, not just running with an empty
#    config.
# 2) Grafana (`control_plane.grafana_url`) answers `/api/health`.
# 3) Alertmanager (`control_plane.alertmanager_url`) answers
#    `/api/v2/status`, if configured (optional -- some deployments run
#    Alertmanager with no external endpoint exposed at all).
# 4) Per pool: `nat_node_healthy` has data -- docs/OBSERVABILITY.md and
#    this suite's own commit history singled out NAT visibility as
#    needing full parity in the observability stack.
#
# -----------------------------------------------------
# Usage:
#
# python run_acceptance_tests.py --only 06-observability
#
# -----------------------------------------------------
# Best Practices:
#
# - Run this LAST (it already is, alphabetically) -- if checks 01-05 have
#   been run first, this check's Prometheus queries are validating real,
#   fresh data generated by this very suite, which is exactly the kind of
#   walkthrough worth recording for a customer demo (see the demo runbook
#   this suite ships alongside, docs/DEMO.md).
